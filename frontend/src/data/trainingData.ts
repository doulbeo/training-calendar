import { TrainingWeek } from '@/types/training';

function ex(name: string, ...lines: [string, string, string, string?][]) {
  let lid = 0;
  return {
    id: '',
    name,
    lines: lines.map(([sets, reps, weight, notes]) => ({
      id: `${++lid}`,
      sets,
      reps,
      weight,
      ...(notes ? { notes } : {}),
    })),
  };
}

function setId(id: string, exercises: ReturnType<typeof ex>[]) {
  return exercises.map((e, i) => ({ ...e, id: `${id}e${i + 1}` }));
}

